#!/usr/bin/env python3
"""Render the black-box interface modules of proved functions.

For every registry entry with an interface (ZesuSsz/Contracts/proved_functions.json)
this writes two declaration-only modules:

- ZesuSsz/Interfaces/<F>.v: a `Module Type` that declares the sealed call-fact
  predicates (`Parameter`), the sealed call spec (the template's body over the
  sealed names) and the interface lemmas (`Axiom`); a module ascribed to it
  opaquely, which realizes each predicate by its real definition and each
  lemma by its hand-written proof (checked once, here); the public call spec;
  and one `ZesuDerivedFacts` instance per registered lemma. Block entries and
  callers import only this module.
- ZesuSsz/Interfaces/<F>Correct.v: the public spec's correctness, from the
  template's correctness, for other functions' compliance composition.

The opaque ascription hides the predicates' bodies from every reduction outside
the sealed module, so no `unfold`, `simpl`, `hnf` or conversion in a caller sees
the callee's meaning. No proof script is emitted.

Usage: render_interfaces.py [--check]
"""
from pathlib import Path
import argparse, json, re, sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/block'))
from entry_seed import definition_body

REGISTRY = ROOT / 'ZesuSsz/Contracts/proved_functions.json'
HEADER = ('(* Generated by tools/block/render_interfaces.py from ZesuSsz/Contracts/proved_functions.json.\n'
          '   Do not edit: change the registry or the proof modules it names and re-render. *)\n')
PROLOGUE = ['Import ListNotations.', 'Local Open Scope Z_scope.', 'Local Open Scope stdpp_scope.']


def module_path(module):
    """The source path of a ZesuSsz logical module name."""
    if not module.startswith('ZesuSsz.'):
        raise ValueError('An interface module must be in ZesuSsz: ' + module)
    return 'ZesuSsz/' + module[len('ZesuSsz.'):].replace('.', '/') + '.v'


def sealed_body(entry):
    """The template call spec's body with each sealed predicate's definition renamed to the sealed name."""
    spec = entry['call_spec']
    body = definition_body((ROOT / spec['template_source']).read_text(), spec['template']).strip()
    for row in entry['sealed']:
        body, count = re.subn(r"(?<![\w.'])" + re.escape(row['definition']) + r"(?![\w'])", row['name'], body)
        if count == 0:
            raise ValueError('The template %s does not state %s' % (spec['template'], row['definition']))
    return body


def statement(lemma):
    return 'forall %s, %s -> %s' % (lemma['binders'], lemma['premise'], lemma['conclusion'])


def interface_text(entry):
    interface, spec = entry['interface'], entry['call_spec']
    sealed = interface['sealed_module']
    body = sealed_body(entry)
    spec_head = '`{!islaG Sigma} `{!threadG} : iProp Sigma'
    sealed_spec = spec['name'] + 'Sealed'
    correct_from = spec['name'] + 'CorrectFrom'
    correct_statement = ('forall `{!islaG Sigma} `{!threadG} (code : iProp Sigma) (entry : Z),\n'
                         '      (⊢ code -∗ instr_body entry %s) ->\n'
                         '      ⊢ code -∗ instr_body entry %s' % (spec['template'], sealed_spec))
    lines = [HEADER.rstrip('\n'), *interface['requires'],
             *('Require Export %s.' % module for module in interface['exports']), *PROLOGUE, '',
             '(* The call-fact predicates of %s, its sealed call spec and its interface' % entry['function'],
             '   lemmas. Outside %s nothing reduces a Parameter. *)' % sealed,
             'Module Type %sSignature.' % sealed]
    lines += ['  Parameter %s : %s.' % (row['name'], row['type']) for row in entry['sealed']]
    lines += ['  Definition %s %s :=\n    %s.' % (sealed_spec, spec_head, body),
              '  Axiom %s : %s.' % (correct_from, correct_statement)]
    lines += ['  Axiom %s : %s.' % (lemma['name'], statement(lemma)) for lemma in entry['interface_lemmas']]
    lines += ['End %sSignature.' % sealed, '',
              '(* Each predicate is its real definition and each lemma its proof, checked once here. *)',
              'Module %s : %sSignature.' % (sealed, sealed)]
    lines += ['  Definition %s : %s := %s.' % (row['name'], row['type'], row['definition'])
              for row in entry['sealed']]
    lines += ['  Definition %s %s :=\n    %s.' % (sealed_spec, spec_head, body),
              '  Definition %s := @%s.' % (correct_from, spec['correct_from'])]
    lines += ['  Definition %s := %s.' % (lemma['name'], lemma['proof']) for lemma in entry['interface_lemmas']]
    lines += ['End %s.' % sealed, 'Export %s.' % sealed, '',
              '(* The public call spec: the template over the sealed predicates. *)',
              'Definition %s %s :=\n  %s.' % (spec['name'], spec_head, body),
              'Global Instance : LithiumUnfold (@%s) := I.' % spec['name'],
              'Global Typeclasses Opaque %s.' % spec['name']]
    registered = [lemma for lemma in entry['interface_lemmas'] if lemma['derived_facts']]
    if registered:
        lines += ['', '(* Facts a caller derives from a forwarded call fact. *)']
    for lemma in registered:
        lines += ['#[export] Instance %sDerivedFacts %s :\n  ZesuDerivedFacts (%s)\n    (%s) :=\n  %s %s.'
                  % (lemma['name'], lemma['binders'], lemma['premise'], lemma['conclusion'],
                     lemma['name'], lemma['binders'])]
    return '\n'.join(lines) + '\n'


def correct_text(entry):
    interface, spec = entry['interface'], entry['call_spec']
    correct = interface['correct']
    premises = ''.join(' (%s : %s)' % (name, kind) for name, kind in correct['premises'])
    arguments = ''.join(' ' + name for name, _ in correct['premises'])
    lines = [HEADER.rstrip('\n'), 'Require Import isla.riscv64.riscv64.',
             'Require Import %s.' % interface['module'], *correct['requires'],
             *('Require Export %s.' % module for module in correct['exports']), 'Local Open Scope Z_scope.', '',
             '(* %s is correct: the sealed spec is the template inside the sealed module. *)' % spec['name'],
             'Definition %s_correct `{!islaG Sigma} `{!threadG}%s :\n  ⊢ %s -∗ instr_body %s %s :=\n'
             '  %sCorrectFrom %s %s (%s%s).'
             % (spec['name'], premises, correct['code'], correct['entry'], spec['name'],
                spec['name'], correct['code'], correct['entry'], correct['template_correct'], arguments)]
    return '\n'.join(lines) + '\n'


def rendered(registry=None):
    """{path: text} of every interface module."""
    registry = registry or json.loads(REGISTRY.read_text())
    result = {}
    for entry in registry['functions']:
        interface = entry.get('interface')
        if not interface:
            continue
        result[module_path(interface['module'])] = interface_text(entry)
        result[module_path(interface['correct']['module'])] = correct_text(entry)
    return result


def stale(registry=None):
    """Paths whose committed text differs from a fresh render, and generated files no entry renders."""
    expected = rendered(registry)
    problems = [path for path, text in sorted(expected.items())
                if not (ROOT / path).exists() or (ROOT / path).read_text() != text]
    problems += [str(path.relative_to(ROOT)) for path in sorted((ROOT / 'ZesuSsz/Interfaces').glob('*.v'))
                 if str(path.relative_to(ROOT)) not in expected]
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail when a committed interface is not fresh')
    options = parser.parse_args()
    if options.check:
        problems = stale()
        if problems:
            raise SystemExit('Interface modules are not fresh (run tools/block/render_interfaces.py): '
                             + ', '.join(problems))
        print('Interface modules are fresh: %d' % len(rendered()))
        return
    for path, text in rendered().items():
        (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / path).write_text(text)
        print(path)


if __name__ == '__main__':
    main()
