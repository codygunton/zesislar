def record(value, keys, label):
    if not isinstance(value, dict) or set(value) != set(keys):
        raise ValueError(f"The {label} has missing or unsupported fields.")
    return value


def sequence(value, label):
    if not isinstance(value, list):
        raise ValueError(f"The {label} must be an ordered list.")
    return value


def identifier(value, label, *, qualified=False):
    pattern = ROCQ_NAME if qualified else re.compile(IDENTIFIER)
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise ValueError(f"The {label} is not a valid Rocq name.")
    return value


def expression(value, label):
    """Reject commands and tactic terms before emitting any expression."""
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"The {label} is not a Rocq expression.")
    stack = []
    pairs = {")": "(", "]": "[", "}": "{"}
    tokens = list(rocq_tokens(value))
    for index, (token, _) in enumerate(tokens):
        if token in FORBIDDEN or token == ".":
            raise ValueError(f"The {label} contains a command or tactic term.")
        if token == ";" and (not stack or stack[-1] not in {"{|", "["}):
            raise ValueError(f"The {label} contains a command or tactic term.")
        if token in {"(", "[", "{"}:
            record_open = token == "{" and index + 1 < len(tokens) and tokens[index + 1][0] == "|"
            stack.append("{|" if record_open else token)
        elif token in pairs:
            expected = pairs[token]
            if token == "}" and stack and stack[-1] == "{|":
                if index == 0 or tokens[index - 1][0] != "|":
                    raise ValueError(f"The {label} has an unfinished record.")
                expected = "{|"
            if not stack or stack.pop() != expected:
                raise ValueError(f"The {label} has mismatched delimiters.")
    if stack:
        raise ValueError(f"The {label} has an unfinished delimiter.")
    return value


def binders(values, reserved=()):
    names = set(reserved)
    result = []
    for item in sequence(values, "binders"):
        record(item, {"name", "type"}, "binder")
        name = identifier(item["name"], "binder name")
        if name in names or name == "Sigma":
            raise ValueError("The binder name is repeated or reserved.")
        names.add(name)
        result.append((name, expression(item["type"], "binder type")))
    return result


def application(predicate, arguments):
    identifier(predicate, "predicate", qualified=True)
    args = [expression(value, "application argument")
            for value in sequence(arguments, "application arguments")]
    return predicate + "".join(f" ({value})" for value in args)


def base_arguments(node):
    """Replace explicit argument positions without interpreting record updates."""
    arguments = [expression(value, "base argument")
                 for value in sequence(node["arguments"], "base arguments")]
    replaced = set()
    for delta in sequence(node["memory_deltas"], "memory deltas"):
        record(delta, {"argument_index", "value"}, "memory delta")
        index = delta["argument_index"]
        if type(index) is not int or not 0 <= index < len(arguments):
            raise ValueError("The memory delta has an invalid argument index.")
        if index in replaced:
            raise ValueError("The memory delta repeats an argument index.")
        replaced.add(index)
        arguments[index] = expression(delta["value"], "memory delta value")
    return arguments


def bound_application(node, fields, root, generated=None):
    """Check the declared arity; Rocq checks the actual argument types."""
    text = application(node["predicate"], node["arguments"])
    name = node["predicate"]
    if generated is not None and name.startswith(generated["module"] + "."):
        if name not in generated["available"]:
            raise ValueError("The generated predicate must precede its reference: " + name)
        if len(node["arguments"]) != generated["available"][name]:
            raise ValueError("The generated predicate application has a different declared arity.")
        return text
    owner, declaration, source = bound_symbol(name, fields, root)
    declared = declared_binders(source, declaration)
    if len(declared) != len(node["arguments"]):
        raise ValueError("The predicate application has a different declared arity.")
    return text


def bound_symbol(name, fields, root):
    """Locate a handwritten declaration in its hash-bound defining module."""
    identifier(name, "source symbol", qualified=True)
    owners = [path for path in fields["source_hashes"]
              if path.endswith(".v") and name.startswith(source_module(path) + ".")]
    if not owners:
        raise ValueError("The source hashes do not bind the predicate: " + name)
    owner = max(owners, key=lambda path: len(source_module(path)))
    declaration = name.rsplit(".", 1)[-1]
    if name != source_module(owner) + "." + declaration:
        raise ValueError("The predicate has an unsupported nested namespace.")
    source = (root / owner).read_text()
    tokens = [token for token, _ in rocq_tokens(source)]
    kinds = {"Definition", "Lemma", "Theorem", "Fact", "Corollary", "Class", "Record",
             "Inductive", "Variant", "Fixpoint", "CoFixpoint", "Instance"}
    declarations = sum(token in kinds and tokens[index + 1:index + 2] == [declaration]
                       for index, token in enumerate(tokens))
    projection = (name == "ZesuSsz.Automation.FactRegistry.zesu_fact_evidence" and
                  any(tokens[index:index + 2] == ["Class", "ZesuFactEvidence"]
                      for index in range(len(tokens) - 1)) and
                  any(tokens[index:index + 2] == [declaration, ":"]
                      for index in range(len(tokens) - 1)))
    if declarations != 1 and not projection:
        raise ValueError("The source lacks one unambiguous declaration: " + name)
    return owner, declaration, source


def expression_references(value, fields, root, generated=None):
    """Check qualified project references without inferring argument types."""
    for token, _ in rocq_tokens(value):
        if generated is not None and (token.startswith(generated["module"] + ".") or
                                       token in generated["declared"]):
            qualified = token if "." in token else generated["module"] + "." + token
            if qualified not in generated["available"]:
                raise ValueError("The generated predicate must precede its reference: " + token)
        elif token.startswith("ZesuSsz.") or any(
                path.endswith(".v") and token.startswith(source_module(path) + ".")
                for path in fields["source_hashes"]):
            bound_symbol(token, fields, root)


def declaration_references(value, fields, root, generated=None):
    if isinstance(value, dict):
        for key, item in value.items():
            if key == "additional_definitions":
                continue
            if key in {"type", "value", "address", "length", "term", "conclusion", "facts"} and isinstance(item, str):
                expression_references(item, fields, root, generated)
            elif key == "arguments" and isinstance(item, list):
                for argument in item:
                    if isinstance(argument, str):
                        expression_references(argument, fields, root, generated)
            else:
                declaration_references(item, fields, root, generated)
    elif isinstance(value, list):
        for item in value:
            declaration_references(item, fields, root, generated)


def pure_component(node, block, fields, root):
    record(node, {"kind", "terms"}, "pure component")
    terms = []
    for item in sequence(node["terms"], "pure terms"):
        record(item, {"term", "provenance"}, "pure term")
        term = expression(item["term"], "pure term")
        provenance = item["provenance"]
        if isinstance(provenance, dict) and provenance.get("kind") == "path":
            record(provenance, {"kind", "from_block", "from_instruction"}, "path provenance")
            if not any(all(edge.get(key) == provenance[key]
                           for key in ("from_block", "from_instruction"))
                       for edge in block.get("incoming_edges", [])):
                raise ValueError("The path provenance names no incoming edge.")
        elif isinstance(provenance, dict) and provenance.get("kind") == "data":
            record(provenance, {"kind", "source"}, "data provenance")
            identifier(provenance["source"], "data source", qualified=True)
            bound_symbol(provenance["source"], fields, root)
        else:
            raise ValueError("The pure term has unsupported provenance.")
        terms.append("(" + term + ")")
    if not terms:
        raise ValueError("The pure component has no terms.")
    return "⌜" + " /\\\n     ".join(terms) + "⌝"


def validate_transition_parameters(block, root):
    """Compare an old entry signature only during the equality transition."""
    fields = contract_fields(block)
    if fields is None:
        raise ValueError("The entry lacks the five executable fields.")
    parameters = binders(fields["binders"])
    declared = check_binders(block, root)
    expected = [(item["name"], normalize_type(item["type"])) for item in declared]
    if [(name, normalize_type(kind)) for name, kind in parameters] != expected:
        raise ValueError("The entry parameters differ from the source Definition.")


def support_declarations(design):
    """Return ordered primary and auxiliary rows without reading source files."""
    if not isinstance(design, dict):
        raise ValueError("The design is not a record.")
    result = []
    names = set()
    for block in sequence(design.get("blocks"), "blocks"):
        if not isinstance(block, dict):
            raise ValueError("The entry row is not a record.")
        if "support" not in block:
            continue
        support = block["support"]
        if not isinstance(support, dict):
            raise ValueError("The entry support is not a record.")
        extras = sequence(support.get("additional_definitions"), "additional definitions")
        before, after = [], []
        for extra in extras:
            record(extra, {"position", "declaration"}, "additional definition")
            if extra["position"] not in {"before", "after"}:
                raise ValueError("The additional definition position is unsupported.")
            declaration = extra["declaration"]
            if not isinstance(declaration, dict) or not isinstance(declaration.get("support"), dict):
                raise ValueError("The additional definition lacks structured support.")
            if declaration["support"].get("additional_definitions") != []:
                raise ValueError("Nested additional definitions are unsupported.")
            (before if extra["position"] == "before" else after).append(declaration)
        for declaration in before + [block] + after:
            fields = contract_fields(declaration)
            if fields is None:
                raise ValueError("The declaration lacks the five executable fields.")
            binders(fields["binders"])
            name = fields["entry_definition"].rsplit(".", 1)[-1]
            if name in names:
                raise ValueError("The entry declaration name is repeated.")
            names.add(name)
            result.append(declaration)
    if not result:
        raise ValueError("The design has no supported entry rows.")
    return result


def component_source(node, block, fields, root, generated):
    if not isinstance(node, dict):
        raise ValueError("The entry component is not a record.")
    kind = node.get("kind")
    if kind == "pure":
        return pure_component(node, block, fields, root)
    if kind == "register":
        record(node, {"kind", "name", "value"}, "register component")
        if not isinstance(node["name"], str) or not re.fullmatch(
                r"x(?:[0-9]|[12][0-9]|3[01])|PC", node["name"]):
            raise ValueError("The register name is unsupported.")
        return f'"{node["name"]}" ↦ᵣ (' + expression(node["value"], "register value") + ")"
    if kind == "register_collection":
        record(node, {"kind", "value"}, "register collection")
        return "reg_col (" + expression(node["value"], "register collection value") + ")"
    if kind in {"byte_array", "unknown_byte_array"}:
        value_key = "value" if kind == "byte_array" else "length"
        record(node, {"kind", "address", value_key}, "memory component")
        address = expression(node["address"], "memory address")
        value = expression(node[value_key], "memory " + value_key)
        operator = "↦ₘ∗" if kind == "byte_array" else "↦ₘ?"
        return f"({address}) {operator} ({value})"
    if kind == "true":
        record(node, {"kind"}, "terminal True")
        return "True"
    if kind == "disjunction":
        record(node, {"kind", "alternatives"}, "disjunction")
        alternatives = sequence(node["alternatives"], "disjunction alternatives")
        if len(alternatives) < 2:
            raise ValueError("The disjunction needs at least two alternatives.")
        rendered = []
        for alternative in alternatives:
            record(alternative, {"kind", "predicate", "arguments"}, "disjunction alternative")
            if alternative["kind"] != "application":
                raise ValueError("The disjunction alternative must be a predicate application.")
            rendered.append("(" + bound_application(alternative, fields, root, generated) + ")")
        return " ∨\n    ".join(rendered)
    if kind in {"base", "application", "continuation"}:
        keys = {"kind", "predicate", "arguments"}
        if kind == "base":
            keys.add("memory_deltas")
        record(node, keys, "predicate component")
        effective = dict(node)
        if kind == "base":
            effective["arguments"] = base_arguments(node)
        return bound_application(effective, fields, root, generated)
    raise ValueError("The entry component kind is unsupported.")


def check_continuation(value, components, fields, root, generated):
    if isinstance(value, dict) and value.get("mode") == "none":
        record(value, {"mode"}, "continuation metadata")
        if any(node["kind"] == "continuation" for node in components):
            raise ValueError("The none mode conceals a continuation component.")
        return
    record(value, {"mode", "component_index", "predicate", "arguments", "order"},
           "continuation metadata")
    if value["mode"] not in {"included_in_base", "explicit"} or value["order"] != "resources_first":
        raise ValueError("The continuation mode or resource order is unsupported.")
    index = value["component_index"]
    kind = "base" if value["mode"] == "included_in_base" else "continuation"
    if type(index) is not int or not 0 <= index < len(components) or components[index]["kind"] != kind:
        raise ValueError("The continuation names no matching component.")
    bound_application(value, fields, root, generated)
    tagged = [node for node in components if node["kind"] == "continuation"]
    matches = [node for node in components if node.get("predicate") == value["predicate"]]
    if value["mode"] == "explicit":
        if (len(tagged) != 1 or len(matches) != 1 or
                components[index]["predicate"] != value["predicate"] or
                components[index]["arguments"] != value["arguments"]):
            raise ValueError("The explicit continuation must match exactly one component.")
    elif tagged or matches or sum(node["kind"] == "base" for node in components) != 1:
        raise ValueError("The entry duplicates its included continuation or base.")


def check_loop(value, locals_, components, fields, root, generated):
    if value is None:
        return
    record(value, {"count", "index", "invariant"}, "loop metadata")
    local_types = dict(locals_)
    loop_names = []
    for key in ("count", "index"):
        binder = record(value[key], {"name", "label"}, "loop " + key)
        name = identifier(binder["name"], "loop binder")
        label = identifier(binder["label"], "loop label")
        if local_types.get(name) != f'lvar "{label}" Z':
            raise ValueError("The loop metadata differs from its lvar binder.")
        loop_names.append(name)
    if loop_names[0] == loop_names[1]:
        raise ValueError("The loop count and index binders must differ.")
    invariant = record(value["invariant"], {"component_index", "predicate", "arguments"},
                       "loop invariant")
    index = invariant["component_index"]
    if type(index) is not int or not 0 <= index < len(components):
        raise ValueError("The loop invariant names no component.")
    node = components[index]
    if (node.get("kind") not in {"base", "application"} or
            any(node[key] != invariant[key] for key in ("predicate", "arguments"))):
        raise ValueError("The loop invariant differs from its component.")
    bound_application(invariant, fields, root, generated)


def entry_source(block, root, generated_paths, generated=None):
    if not isinstance(block, dict):
        raise ValueError("The entry row is not a record.")
    fields = contract_fields(block)
    if fields is None:
        raise ValueError("The entry lacks the five executable fields.")
    parameters = binders(fields["binders"])
    for value in fields["arguments"]:
        expression(value, "entry argument")
    if generated_paths.intersection(fields["source_hashes"]):
        raise ValueError("The profile binds a generated output as an input source.")
    verify_sources(fields, root)
    declaration_references({"binders": fields["binders"], "arguments": fields["arguments"],
                            "support": block["support"]}, fields, root, generated)
    support = block.get("support")
    keys = {
        "version", "existentials", "components", "loop", "continuation",
        "additional_definitions"}
    if not isinstance(support, dict) or not keys.issubset(support) or set(support) - keys - {"lets"}:
        raise ValueError("The entry support has missing or unsupported fields.")
    if type(support["version"]) is not int or support["version"] != 1:
        raise ValueError("The entry support version is unsupported.")
    reserved = [name for name, _ in parameters]
    lets = []
    for item in sequence(support.get("lets", []), "local lets"):
        record(item, {"name", "type", "value"}, "local let")
        [(name, kind)] = binders([{"name": item["name"], "type": item["type"]}], reserved)
        reserved.append(name)
        lets.append((name, kind, expression(item["value"], "local let value")))
    locals_ = binders(support["existentials"], reserved)
    components = sequence(support["components"], "entry components")
    if not components:
        raise ValueError("The entry has no body components.")
    atoms = [component_source(node, block, fields, root, generated) for node in components]
    check_continuation(support["continuation"], components, fields, root, generated)
    check_loop(support["loop"], locals_, components, fields, root, generated)
    name = identifier(fields["entry_definition"].rsplit(".", 1)[-1], "entry name")
    typed = "".join(f" ({name} : {kind})" for name, kind in parameters)
    body = " ∗\n   ".join("(" + atom + ")" for atom in atoms)
    if locals_:
        body = "∃ " + " ".join(f"({name} : {kind})" for name, kind in locals_) + ",\n   " + body
    let_source = "".join(f"let {name} : {kind} := ({value}) in\n  " for name, kind, value in lets)
    return name, (f"Definition {name} `{{!islaG Sigma}} `{{!threadG}}\n"
                  f"   {typed} : iProp Sigma :=\n  {let_source}({body})%I.\n")


def imports(values):
    result = []
    seen = set()
    for item in sequence(values, "imports"):
        record(item, {"mode", "module"}, "import")
        if item["mode"] not in {"import", "export"}:
            raise ValueError("The import mode is unsupported.")
        module = identifier(item["module"], "import module", qualified=True)
        if module in seen:
            raise ValueError("The import module is repeated.")
        seen.add(module)
        result.append(f"Require {item['mode'].capitalize()} {module}.")
    return result


def fact_source(value, fields, root):
    """Render the reviewed evidence-backed fact constructor, never a script."""
    record(value, {"name", "parameters", "premises", "conclusion", "lemma",
                   "arguments", "explicit_lemma", "priority", "locality"}, "fact registration")
    name = identifier(value["name"], "fact registration name")
    bound_symbol(value["lemma"], fields, root)
    for helper in ("zesu_simpl_and_fact", "ZesuFactEvidence", "zesu_fact_evidence"):
        bound_symbol("ZesuSsz.Automation.FactRegistry." + helper, fields, root)
    declaration_references(value, fields, root)
    if value["locality"] not in {"local", "global", "export"}:
        raise ValueError("The fact registration locality is unsupported.")
    if value["priority"] is not None and (type(value["priority"]) is not int or value["priority"] < 0):
        raise ValueError("The fact registration priority is invalid.")
    if type(value["explicit_lemma"]) is not bool:
        raise ValueError("The explicit lemma flag must be Boolean.")
    names = set()
    parameters = []
    for field in ("parameters", "premises"):
        for binder in sequence(value[field], "fact " + field):
            record(binder, {"name", "type", "implicit"}, "fact binder")
            bound = identifier(binder["name"], "fact binder name")
            if bound in names or bound == name:
                raise ValueError("The fact binder name is repeated or reserved.")
            names.add(bound)
            kind = expression(binder["type"], "fact binder type")
            if type(binder["implicit"]) is not bool:
                raise ValueError("The fact binder implicit flag must be Boolean.")
            if field == "premises":
                kind = "ZesuSsz.Automation.FactRegistry.ZesuFactEvidence (" + kind + ")"
            opening, closing = ("{", "}") if binder["implicit"] else ("(", ")")
            parameters.append(f"{opening}{bound} : {kind}{closing}")
    conclusion = expression(value["conclusion"], "fact conclusion")
    constructor = application(value["lemma"], value["arguments"])
    if value["explicit_lemma"]:
        constructor = "@" + constructor
    source = f"#[{value['locality']}] Instance {name}"
    source += "".join(" " + binder for binder in parameters)
    priority = "" if value["priority"] is None else f" | {value['priority']}"
    source += f" : SimplAnd ({conclusion}) True{priority} :=\n"
    source += "  ZesuSsz.Automation.FactRegistry.zesu_simpl_and_fact (" + constructor + ").\n"
    return name, source


def introduction_source(value, fields, root, generated):
    """Render an existing entry introduction by direct lemma application."""
    record(value, {"name", "iris_contexts", "parameters", "class", "source", "facts",
                   "lemma", "arguments", "explicit_lemma", "priority", "locality"},
           "entry introduction")
    name = identifier(value["name"], "introduction name")
    if value["locality"] not in {"local", "global", "export"}:
        raise ValueError("The introduction locality is unsupported.")
    if value["priority"] is not None and (type(value["priority"]) is not int or value["priority"] < 0):
        raise ValueError("The introduction priority is invalid.")
    if type(value["explicit_lemma"]) is not bool:
        raise ValueError("The explicit lemma flag must be Boolean.")
    bound_symbol(value["class"], fields, root)
    bound_symbol(value["lemma"], fields, root)
    declaration_references(value, fields, root, generated)
    contexts = []
    for context in sequence(value["iris_contexts"], "Iris contexts"):
        expression(context, "Iris context")
        expression_references(context, fields, root, generated)
        if context not in {"!islaG Sigma", "!threadG"} or context in contexts:
            raise ValueError("The Iris context is repeated or unsupported.")
        contexts.append(context)
    typed = "".join(" `{" + context + "}" for context in contexts)
    names = {"Sigma", name}
    for binder in sequence(value["parameters"], "introduction parameters"):
        record(binder, {"name", "type", "implicit"}, "introduction parameter")
        bound = identifier(binder["name"], "introduction parameter name")
        if bound in names:
            raise ValueError("The introduction parameter name is repeated or reserved.")
        names.add(bound)
        kind = expression(binder["type"], "introduction parameter type")
        if type(binder["implicit"]) is not bool:
            raise ValueError("The introduction parameter implicit flag must be Boolean.")
        opening, closing = ("{", "}") if binder["implicit"] else ("(", ")")
        typed += f" {opening}{bound} : {kind}{closing}"
    source_node = record(value["source"], {"predicate", "arguments"}, "introduction source")
    entry = bound_application(source_node, fields, root, generated)
    facts = expression(value["facts"], "introduction facts")
    constructor = application(value["lemma"], value["arguments"])
    if value["explicit_lemma"]:
        constructor = "@" + constructor
    priority = "" if value["priority"] is None else f" | {value['priority']}"
    target = value["class"] + " (" + entry + ") (" + facts + ")"
    return name, f"#[{value['locality']}] Instance {name}{typed} : {target}{priority} :=\n  {constructor}.\n"


def scoped_imports(values):
    result = {"entries": [], "registrations": []}
    seen = set()
    for value in sequence(values, "scoped imports"):
        record(value, {"target", "module"}, "scoped import")
        target, module = value["target"], value["module"]
        if target not in result:
            raise ValueError("The scoped import target is unsupported.")
        if not isinstance(module, str) or not re.fullmatch(IDENTIFIER + r"(?:\." + IDENTIFIER + r")*", module):
            raise ValueError("The scoped import module is not a valid Rocq name.")
        if (target, module) in seen:
            raise ValueError("The scoped import is repeated.")
        seen.add((target, module))
        result[target].append("Import " + module + ".")
    return result


def scope_names(values, label):
    names = [identifier(value, label) for value in sequence(values, label + "s")]
    if len(set(names)) != len(names):
        raise ValueError("The scope name is repeated.")
    return names


def unfold_pairs(names):
    lines = []
    for name in names:
        lines.extend([f"Global Instance : LithiumUnfold (@{name}) := I.",
                      f"Global Typeclasses Opaque {name}.", ""])
    return lines


def bootstrap_source(value, root, generated, ordinary_sources):
    """Render a registry that imports only its defining modules and class."""
    keys = {"imports", "source_hashes", "unfold_sources"}
    if (not isinstance(value, dict) or not keys.issubset(value) or
            set(value) - keys - {"regcol_unfold_sources"}):
        raise ValueError("The bootstrap has missing or unsupported fields.")
    lines = imports(value["imports"])
    if any(item["mode"] != "import" for item in value["imports"]):
        raise ValueError("The bootstrap imports must use import mode.")
    fields = contract_fields({"entry_definition": "Support.Source.input",
                              "resource_predicate": "Support.Source.input", "binders": [],
                              "arguments": [], "source_hashes": value["source_hashes"]})
    if any(path.startswith("ZesuSsz/Generated/") for path in fields["source_hashes"]):
        raise ValueError("The bootstrap binds a generated output as an input source.")
    verify_sources(fields, root)
    owners = set()
    lists = {}
    for key in ("unfold_sources", "regcol_unfold_sources"):
        names = [identifier(name, "bootstrap source", qualified=True)
                 for name in sequence(value.get(key, []), key)]
        if len(set(names)) != len(names):
            raise ValueError("The bootstrap source is repeated.")
        for name in names:
            if (name.startswith("ZesuSsz.Generated.") or
                    name.rsplit(".", 1)[-1] in generated["declared"] or
                    name in ordinary_sources):
                raise ValueError("The bootstrap source overlaps another generated registration.")
            owner, _, _ = bound_symbol(name, fields, root)
            owners.add(source_module(owner))
        lists[key] = names
    modules = {item["module"] for item in value["imports"]}
    if modules != owners | {"isla.automation"}:
        raise ValueError("The bootstrap must import exactly its defining modules and isla.automation.")
    lines += [""] + unfold_pairs(lists["unfold_sources"])
    lines += [f"Global Hint Unfold {name} : regcol_compute_unfold."
              for name in lists["regcol_unfold_sources"]]
    return HEADER + "\n".join(lines).rstrip() + "\n"


def render_support(design, root, *, name_prefix="decodeItem"):
    """Validate both outputs before a caller writes either output."""
    root = Path(root)
    names = FunctionNames(name_prefix)
    if not isinstance(design, dict) or not isinstance(design.get("function"), str):
        raise ValueError("The design must name its function.")
    if design["function"].rsplit(".", 1)[-1] != names.prefix:
        raise ValueError("The design names a different function.")
    metadata = design.get("support")
    keys = {
        "version", "entries_imports", "entries_scopes", "registrations_imports",
        "unfold_entries", "introductions", "hint_umbrella", "scoped_imports", "facts"}
    if (not isinstance(metadata, dict) or not keys.issubset(metadata) or
            set(metadata) - keys - {"source_hashes", "registrations_scopes", "unfold_sources", "bootstrap"}):
        raise ValueError("The function support has missing or unsupported fields.")
    if type(metadata["version"]) is not int or metadata["version"] != 1:
        raise ValueError("The function support version is unsupported.")
    entry_imports = imports(metadata["entries_imports"])
    registration_imports = imports(metadata["registrations_imports"])
    umbrella = imports(metadata["hint_umbrella"])
    scoped = scoped_imports(metadata["scoped_imports"])
    scopes = scope_names(metadata["entries_scopes"], "scope")
    registration_scopes = scope_names(metadata.get("registrations_scopes", []), "registration scope")
    directory = Path("ZesuSsz/Generated") / names.module
    generated_paths = {str(directory / filename) for filename in
                       ("Entries.v", "Registrations.v", "BootstrapRegistrations.v")}
    rows = support_declarations(design)
    generated = {"module": str(directory / "Entries").replace("/", "."), "available": {},
                 "declared": {row["entry_definition"].rsplit(".", 1)[-1] for row in rows}}
    entries = []
    for block in rows:
        name, source = entry_source(block, root, generated_paths, generated)
        entries.append((name, source))
        generated["available"][generated["module"] + "." + name] = len(block["binders"])
    declarations = [name for name, _ in entries]
    fact_records = sequence(metadata["facts"], "fact registrations")
    intro_records = sequence(metadata["introductions"], "entry introductions")
    facts = []
    introductions = []
    unfold_sources = [identifier(value, "unfold source", qualified=True)
                      for value in sequence(metadata.get("unfold_sources", []), "unfold sources")]
    if (len(set(unfold_sources)) != len(unfold_sources) or
            any(name.rsplit(".", 1)[-1] in declarations or
                name.startswith("ZesuSsz.Generated.") for name in unfold_sources)):
        raise ValueError("The unfold source is repeated or overlaps a generated declaration.")
    if fact_records or intro_records or unfold_sources or "source_hashes" in metadata:
        fields = contract_fields({"entry_definition": "Support.Source.input",
                                  "resource_predicate": "Support.Source.input", "binders": [],
                                  "arguments": [], "source_hashes": metadata.get("source_hashes")})
        if generated_paths.intersection(fields["source_hashes"]):
            raise ValueError("The profile binds a generated output as an input source.")
        verify_sources(fields, root)
        for name in unfold_sources:
            bound_symbol(name, fields, root)
        facts = [fact_source(value, fields, root) for value in fact_records]
        introductions = [introduction_source(value, fields, root, generated) for value in intro_records]
    fact_names = [name for name, _ in facts + introductions]
    if len(set(fact_names)) != len(fact_names) or set(fact_names).intersection(declarations):
        raise ValueError("The fact registration name is repeated or conflicts with an entry.")
    if facts and not any(item["module"] == "ZesuSsz.Automation.FactRegistry"
                         for item in metadata["registrations_imports"]):
        raise ValueError("Fact registrations require the defining FactRegistry import.")
    if len(set(declarations)) != len(declarations):
        raise ValueError("The entry declaration name is repeated.")
    registered = sequence(metadata["unfold_entries"], "unfold entries")
    for name in registered:
        identifier(name, "unfold entry")
    if len(set(registered)) != len(registered) or set(registered) != set(declarations):
        raise ValueError("The unfold list must name each rendered entry once.")
    entries_text = HEADER + "\n".join(entry_imports + scoped["entries"] + [f"Open Scope {scope}." for scope in scopes]) + "\n\n"
    entries_text += "\n".join(source for _, source in entries)
    registration_lines = registration_imports + [f"Require Export ZesuSsz.Generated.{names.module}.Entries."]
    registration_lines += scoped["registrations"]
    registration_lines += [f"Open Scope {scope}." for scope in registration_scopes] + [""]
    # Keep generated pairs first, then the supplied handwritten-source order.
    registration_lines.extend(unfold_pairs(registered + unfold_sources))
    registration_lines.extend(source.rstrip() + "\n" for _, source in facts)
    registration_lines.extend(source.rstrip() + "\n" for _, source in introductions)
    registration_lines.extend(umbrella)
    registrations_text = HEADER + "\n".join(registration_lines).rstrip() + "\n"
    outputs = {directory / "Entries.v": entries_text,
               directory / "Registrations.v": registrations_text}
    if "bootstrap" in metadata:
        outputs[directory / "BootstrapRegistrations.v"] = bootstrap_source(
            metadata["bootstrap"], root, generated, unfold_sources)
    return outputs


def validate_support(design, root, *, name_prefix="decodeItem"):
    """Validate supported rows without old entry lookups or output reads/writes.

    The design generator must validate legacy rows through its existing path.
    The unfold list names exactly the supported rows in a mixed design.
    """
    render_support(design, root, name_prefix=name_prefix)


def unique_object(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError("The input contains a duplicate JSON key: " + key)
        result[key] = value
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--function", type=prefix_argument, default="decodeItem")
    parser.add_argument("--design", type=Path)
    parser.add_argument("--check", action="store_true", help="Check output bytes without writing files.")
    args = parser.parse_args()
    names = FunctionNames(args.function)
    path = args.design or ROOT / f"ZesuSsz/Evidence/{names.filename}_block_design.json"
    design = json.loads(path.read_text(), object_pairs_hook=unique_object)
    outputs = render_support(design, ROOT, name_prefix=args.function)
    if args.check:
        for relative, source in outputs.items():
            target = ROOT / relative
            if not target.is_file() or target.read_bytes() != source.encode():
                raise ValueError("The generated support is stale: " + str(relative))
    else:
        for relative in outputs:
            target = ROOT / relative
            if target.exists() and not target.read_bytes().startswith(HEADER.encode()):
                raise ValueError("The output would replace handwritten source: " + str(relative))
        for relative, source in outputs.items():
            target = ROOT / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(source)


if __name__ == "__main__":
    main()
