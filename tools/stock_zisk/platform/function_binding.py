"""Bind one selected function to existing validated closure instruction modules."""
import hashlib
import json
from pathlib import Path
import re
import tempfile

from exports import native_prefix, render_exports, validate_exports
from indexes import FUNCTION_NAMES, validate_indexes


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def selected_code(prefix, logical_module):
    return ("(* Generated by bind_traces.py; instruction resources only. *)\n"
            "Require Import isla.riscv64.riscv64.\n"
            f"Require Import {logical_module}.\n"
            "Require Import ZesuSsz.Contracts.SelectedCodeLookup.\n"
            "Require Import InstrSpecs.Lookup.\n\n"
            f"Definition {prefix}SelectedCode `{{!islaG Sigma}} `{{!threadG}} : iProp Sigma :=\n"
            "  instr_lookup_resources\n"
            f"    (selectedCodeLookup {logical_module}.instr_map).\n\n"
            f"Global Instance : LithiumUnfold (@{prefix}SelectedCode) := I.\n"
            f"Global Typeclasses Opaque {prefix}SelectedCode.\n")


def prepare(root, source, function_name, trace_name):
    """Return derived sources only after validating exact selected coverage."""
    root, source = Path(root).resolve(), Path(source).resolve()
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", trace_name):
        raise ValueError("The selected trace name is not an identifier.")
    inventory_path = root / "build/stock-zisk/inventory.json"
    inventory = json.loads(inventory_path.read_text())
    functions = [function for function in inventory["functions"] if function["name"] == function_name]
    if len(functions) != 1 or FUNCTION_NAMES.get(function_name) is None:
        raise ValueError("The function has no single approved closure index.")
    function = functions[0]
    region = FUNCTION_NAMES[function_name]
    coverage_path = source / "coverage.json"
    coverage = json.loads(coverage_path.read_text())
    elf = root / "build/stock-zisk/zesu-zisk.elf"
    if coverage["elf_sha256"] != digest(elf) or inventory["elf_sha256"] != coverage["elf_sha256"]:
        raise ValueError("The selected coverage binds a different ELF.")
    for field, relative in (("platform_snapshot_sha256", "build/stock-zisk/platform/riscv64-zisk.ir"),
                            ("config_sha256", "ZesuSsz/riscv64_zesu.toml")):
        if coverage[field] != digest(root / relative):
            raise ValueError("The selected trace input changed: " + field)
    pcs = {row["pc"] for row in function["rows"]}
    region_pcs = {int(pc, 0) for pc in coverage["indexes"]["regions"][region]}
    if len(pcs) != len(function["rows"]) or region_pcs != pcs:
        raise ValueError("The closure index does not cover the complete selected function.")
    index = source / f"index_{region}.v"
    with tempfile.TemporaryDirectory(prefix="selected-function-index-") as temporary:
        selected = Path(temporary)
        (selected / index.name).symlink_to(index)
        validate_indexes(selected, {region: pcs}, coverage["indexes"]["coqdir"])
    commitment = coverage["commitments"][region]
    if commitment["function"] != function_name or commitment["unmodeled_instruction_pcs"]:
        raise ValueError("The selected commitment has another function or unsupported instructions.")
    expected = [{"pc": hex(row["pc"]), "bytes": row["word"].to_bytes(row["size"], "little").hex()}
                for row in sorted(function["rows"], key=lambda row: row["pc"])]
    if commitment["instruction_bytes"] != expected:
        raise ValueError("The selected instruction bytes differ from the inventory.")
    validate_exports(index, region, commitment)
    files = {Path(name).name: sha for name, sha in coverage["files"].items()}
    inputs = {str(inventory_path): digest(inventory_path), str(coverage_path): digest(coverage_path),
              str(elf): digest(elf), str(index): digest(index)}
    if files.get(index.name) != digest(index):
        raise ValueError("The selected index differs from the coverage record.")
    for pc in sorted(pcs):
        for suffix in ("v", "isla"):
            path = source / f"a{pc:x}.{suffix}"
            if files.get(path.name) != digest(path):
                raise ValueError("A selected instruction module changed: " + path.name)
            inputs[str(path)] = digest(path)
    destination = root / "generated/isla-traces/stock-zisk" / trace_name
    if destination.resolve() == source:
        raise ValueError("The derived index must not replace the closure index directory.")
    prefix = function_name.rsplit(".", 1)[-1]
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", prefix):
        raise ValueError("The selected function prefix is not an identifier.")
    namespace = trace_name[0].upper() + trace_name[1:]
    theory = f"ZesuSsz.Stock.{namespace}"
    logical_module = f"{theory}.index_{prefix}"
    output = {
        destination / f"index_{prefix}.v": native_prefix(index.read_text()) + render_exports(prefix, commitment),
        destination / "dune": (
            "; Generated by bind_traces.py; reuses the validated closure modules.\n"
            f"(coq.theory\n (name {theory})\n"
            " (flags :standard -w -notation-overridden -w -redundant-canonical-projection)\n"
            f" (theories {coverage['indexes']['coqdir']} isla isla.riscv64 lithium iris stdpp RecordUpdate Ltac2 ZesuStock))\n"),
        root / f"ZesuSsz/Contracts/{prefix[0].upper() + prefix[1:]}Selected.v": selected_code(prefix, logical_module),
    }
    return output, {"function": function_name, "trace_name": trace_name,
                    "instruction_count": len(pcs), "logical_module": logical_module,
                    "source_hashes": inputs, "native_prefix_unchanged": True,
                    "scope": "Instruction resources and byte/CFG commitments; no semantic contract proof"}


def bind(root, source, function_name, trace_name, *, check=False):
    outputs, report = prepare(root, source, function_name, trace_name)
    for path, text in outputs.items():
        if check:
            if not path.is_file() or path.read_text() != text:
                raise ValueError("The selected binding is stale: " + str(path))
        elif path.exists() and path.read_text() != text:
            raise ValueError("The selected binding has different existing source: " + str(path))
    if not check:
        for path, text in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    report["generated_sha256"] = {str(path): digest(path) for path in outputs}
    return report
