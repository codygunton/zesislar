#!/usr/bin/env python3
"""Rank the automation opportunities the replay found.

One row per gap pattern: the class of the goal the automation stopped at and
the tactic the author used next. Ranked by hand lines saved, which is what
the lead hands to the compliance orchestrator top down.

The remedy column repeats the table of section 9. It is a proposal, not a
patch: this plan never edits an automation file.
"""

from __future__ import annotations

import argparse
import collections
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from replay_report import goal_shape, needed_pairs, read, replayed  # noqa: E402

OUTPUT = Path("ZesuSsz/Evidence/residuals/AUTOMATION_BACKLOG.md")

# class -> (remedy, owner, size). Section 9 fixes the remedies and the owners.
REMEDY = {
    "C1": ("Compute the events term in the postcondition and close the trace"
           " side condition inside `zesu_finish`, with the `unfold subseteq,"
           " spec_subseteq, scons, scons_snap; naive_solver` line that every"
           " segment proof repeats.", "auto, then orchestrator", "half day"),
    "C2": ("Add array slice subsumption and word-in-array rules, so a take,"
           " a drop or one word of an array needs no hand step.",
           "auto", "day"),
    "C3": ("Apply the `_unfold` lemma, or register a `LithiumUnfold`"
           " instance, at the closed-contract exit.", "auto", "half day"),
    "C4": ("Add the closing shapes to the finisher; `bv_solve` already"
           " closes most of them.", "auto", "hour"),
    "C6": ("State the precondition inside `instr_body` so Lithium introduces"
           " it, and give the named predicate a `LithiumUnfold` instance.",
           "orchestrator for new lemmas", "half day"),
    "C7": ("Register the code bundle names in `zesu_expose_code_lists`.",
           "auto", "hour"),
    "C8": ("Give the spec a known shape, or add a `case_destruct` hook for"
           " the bare match.", "orchestrator for new specs", "half day"),
    "error": ("The automation raises at this state. Diagnose before any"
              " rule: a raising tactic hides every gap behind it.",
              "auto", "half day"),
    "unknown": ("No class covers this goal yet. Read the goal head in the"
                " corpus before proposing a rule.", "lead", "unknown"),
    "closed": ("The automation already finishes here; the line is dead"
               " weight.", "orchestrator", "hour"),
    "unseen": ("Structural sentence, a bullet or a brace. No rule applies.",
               "none", "none"),
}
SKIP = {"unseen"}


def rows(records: list[dict]) -> list[dict]:
    done = replayed(records)
    lines = collections.Counter()
    proofs = collections.defaultdict(set)
    heads = collections.defaultdict(collections.Counter)
    for record in done:
        steps = {step["index"]: step for step in record["steps"]}
        for index, (shape, tactic) in enumerate(needed_pairs(record), start=1):
            if shape in SKIP:
                continue
            key = (shape, tactic)
            lines[key] += 1
            proofs[key].add((record["module"], record["lemma"]))
            before = steps.get(index - 1)
            if before and before["goal_head"]:
                heads[key][before["goal_head"][0][:70]] += 1
    ranked = []
    for (shape, tactic), count in lines.most_common():
        remedy, owner, size = REMEDY.get(shape, REMEDY["unknown"])
        head = heads[(shape, tactic)].most_common(1)
        ranked.append({"class": shape, "tactic": tactic,
                       "proofs": len(proofs[(shape, tactic)]),
                       "lines": count, "remedy": remedy, "owner": owner,
                       "size": size,
                       "head": head[0][0] if head else "-"})
    return ranked


def dead_weight(records: list[dict]) -> tuple[int, int]:
    """Proofs that finish early, and the sentences after their `closes_at`."""
    done = replayed(records)
    early = [r for r in done if r["closes_at"] is not None]
    saved = sum(max(0, r["n_sentences"] - 1 - r["closes_at"]) for r in early)
    return len(early), saved


def document(records: list[dict], title: str, limit: int) -> str:
    ranked = rows(records)
    early, saved = dead_weight(records)
    done = replayed(records)
    total = sum(row["lines"] for row in ranked)
    text = [f"# Automation backlog ({title})", "",
            "Generated by `tools/residual/backlog.py` from the E1 replay of",
            "`PLAN_RESIDUAL_CORPUS.md` section 10. One row per gap pattern:",
            "the class of the goal at which the block automation stopped, and",
            "the tactic the author wrote next. Ranked by hand lines saved.",
            "",
            "This file proposes rules. It never patches one: the compliance",
            "orchestrator owns every change to `ZesuSsz/Automation/`.", "",
            f"Replays read: {len(records)}, of which {len(done)} completed.",
            f"Proofs the automation already finishes before their last line:",
            f"{early} of {len(done)}, leaving {saved} sentences that are dead",
            f"weight today. Needed hand lines counted: {total}.", "",
            "| rank | class | hand line | proofs | lines | size | owner |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    for rank, row in enumerate(ranked[:limit], start=1):
        text.append(f"| {rank} | {row['class']} | `{row['tactic']}` | "
                    f"{row['proofs']} | {row['lines']} | {row['size']} | "
                    f"{row['owner']} |")
    text += ["", "## Proposed rules, by class", ""]
    seen = []
    for row in ranked[:limit]:
        if row["class"] in seen:
            continue
        seen.append(row["class"])
        total_lines = sum(r["lines"] for r in ranked if r["class"] == row["class"])
        total_proofs = len({p for r in ranked if r["class"] == row["class"]
                            for p in [r["tactic"]]})
        text += [f"### {row['class']} — {total_lines} hand lines, "
                 f"{total_proofs} tactic shapes", "",
                 row["remedy"], "",
                 f"Most common goal head: `{row['head']}`", ""]
    return "\n".join(text) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replay", type=Path,
                        default=Path("ZesuSsz/Evidence/residuals/replay.jsonl"))
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--title", default="v1, rule-15 era and tier 1")
    parser.add_argument("--limit", type=int, default=25)
    arguments = parser.parse_args()
    records = read(arguments.replay)
    arguments.output.write_text(document(records, arguments.title,
                                         arguments.limit))
    print(f"{arguments.output}: {len(rows(records))} gap patterns")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
