#!/usr/bin/env python3
"""WP5: generate a segment module, with no hand-written proof line.

A straight-line segment is one module: its boundary predicates, one
`instr_body` lemma, and `Proof. move => *. zesu_block. Qed.` Everything
else the module needs -- the imports, the code premise, the binders -- is
derived, so the only Rocq a person writes for the segment is the boundary
names, and WP4 derives those too once a boundary can be inferred.

The statement comes from the segment's own interface: the binders and the
boundary predicates the merged module already states. Three things change:

- the code premise becomes `instr_lookup_resources` and
  `spec_instr_resources`, which the automation can use, instead of a
  folded bundle it cannot see through. That alone is the corpus's largest
  gap, 122 proofs and 888 hand lines.
- the proof body is the block automation alone.
- the module imports `Automation.All`, plus any rule the segment opts
  into, such as `Automation.WordArrayBytes`.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "residual"))

from infer_boundary import CODE_PREMISES, with_standard_code  # noqa: E402
from modules import find_proof  # noqa: E402

PROOF_DIR = Path("ZesuSsz/Proofs/WriteSuccess")
# Generated modules live under Evidence until they compile. A module that
# does not close belongs nowhere near `check-iris`: the gate would fail on
# work in progress and stop saying anything about the rest.
GENERATED_DIR = Path("ZesuSsz/Evidence/det/wp5/generated")
SCRATCH = Path("tools/coqc_scratch.sh")
REQUIRED = "Require Import ZesuSsz.Automation.All."
V2_IMPORT = "Require Import ZesuSsz.Automation.Sets.v2."


OPENER = ("Require ", "From ", "Import ", "Open Scope")


def source_imports(lines: list[str]) -> list[str]:
    """The requires of the module the statement came from, plus ours.

    A `From … Require Import` often runs over several lines, so this
    collects whole sentences rather than lines; taking only the first
    line of one drops most of its imports.
    """
    wanted: list[str] = []
    current: list[str] = []
    for line in lines:
        if current:
            current.append(line)
        elif line.startswith(OPENER):
            current = [line]
        else:
            continue
        if line.rstrip().endswith("."):
            wanted.append("\n".join(current))
            current = []
    if REQUIRED not in wanted:
        wanted.insert(0, REQUIRED)
    if V2_IMPORT not in wanted:
        wanted.append(V2_IMPORT)
    return wanted


def generate(module: Path, lemma: str, extra: list[str]) -> tuple[str, str]:
    """The generated module text and the name of its lemma."""
    proof = find_proof(module, lemma)
    lines = module.read_text().split("\n")
    statement = with_standard_code(
        lines[proof.declaration_line:proof.proof_line])
    name = f"{lemma}_generated"
    statement = [line.replace(lemma, name) for line in statement]
    header = source_imports(lines[:proof.declaration_line])
    header += [f"Require Import {name}." for name in extra]
    body = ["Proof. move => *. zesu_block. Qed.",
            f"Print Assumptions {name}."]
    return "\n".join(
        ["(* Generated by tools/det/gen_segment.py. Do not edit: the proof",
         "   is the block automation, and any line added here is a line the",
         "   automation is missing. Regenerate instead. *)"]
        + header + [""] + statement + body + [""]), name


def compile_module(path: Path, build_dir: Path, seconds: int) -> dict:
    """Build one generated module inside the theory, then take it out.

    The generated modules live under `Evidence`, which Dune does not
    build. Compiling one means copying it into the proof directory for
    the length of the build and removing it afterwards, so a module that
    does not close never reaches the gate.
    """
    staged = PROOF_DIR / path.name
    staged.write_text(path.read_text())
    try:
        return _build_staged(staged, build_dir, seconds)
    finally:
        staged.unlink(missing_ok=True)


def _build_staged(path: Path, build_dir: Path, seconds: int, *, jobs: int = 4) -> dict:
    guard = Path("tools/resource_guard.sh")
    launcher = ([str(guard), "scope", f"gen-{path.stem[:30]}", "--"]
                if guard.exists() else [])
    started = time.monotonic()
    environment = dict(os.environ)
    for credential in ("ARISTOTLE_API_KEY", "OPEN_ROUTER_API_KEY", "PROVER_API_KEY"):
        environment.pop(credential, None)
    done = subprocess.run(
        [*launcher, "nice", "-n", "10", "opam", "exec", "--switch",
         str(Path.home() / "islaris"), "--", "dune", "build", "--root", ".",
         "--build-dir", str(Path(build_dir).resolve()), "--cache=enabled",
         f"-j{jobs}", str(path.with_suffix(".vo"))],
        capture_output=True, text=True, timeout=seconds + 60, env=environment)
    output = done.stdout + "\n" + done.stderr
    errors = [line for line in output.split("\n")
              if line.startswith("Error") or "Tactic failure" in line]
    return {"compiled": done.returncode == 0,
            "seconds": round(time.monotonic() - started, 1),
            "errors": errors[:4]}


def from_spec(spec: dict, extra_imports: list[str], *,
              strict: bool = False) -> tuple[str, str]:
    """A segment module from a spec record, not from an existing module.

    Chain generation has no merged module to read a statement out of: the
    entry predicate is the previous junction's inferred boundary and the
    exit predicate is this junction's. Everything else the statement
    needs -- the code premise, one call premise per call site -- comes
    from the address range.
    """
    from call_sites import premises as call_premises  # noqa: PLC0415

    entry = int(spec["entry"], 16)
    exit_address = int(spec["exit"], 16)
    calls, call_modules, _unknown = call_premises(entry, exit_address,
                                                strict=strict)
    imports = (["Require Import isla.riscv64.riscv64.",
                "From IslaTraces.write_success_blocks Require Import Index."]
               + [f"Require Import {name}."
                  for name in list(spec["imports"]) + call_modules
                  + list(extra_imports)])
    name = spec["name"]
    successors = spec.get("successors")
    exits = ([line for successor in successors
              for line in [f"  instr_pre {successor['address']}",
                           f"    ({successor['spec']}) -∗"]]
             if successors is not None else
             [f"  instr_body {spec['exit']}",
              f"    ({spec['exit_spec']}) -∗"])
    body = ([f"Lemma {name}", f"    {spec['binders']} :"]
            + CODE_PREMISES + calls
            + exits + [f"  instr_body {spec['entry']}",
               f"    ({spec['spec']}).",
               "Proof. zesu_block. Qed.",
               "",
               f"Print Assumptions {name}."])
    header = [
        "(* Generated by tools/det/gen_segment.py. Do not edit.",
        "",
        f"   {spec['entry']} to {spec['exit']}. Both boundary predicates",
        "   are inferred, and the proof is the block automation alone. *)",
        "",
    ]
    return "\n".join(header + imports + [""] + body) + "\n", name


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--set", type=Path, default=None,
                        help="one MODULE:LEMMA[:EXIT] per line")
    parser.add_argument("--specs", type=Path, default=None,
                        help="segment records with both boundaries named")
    parser.add_argument("--extra-import", action="append", default=[])
    parser.add_argument("--build-dir", type=Path,
                        default=Path("_build/agents/det"))
    parser.add_argument("--out-dir", type=Path, default=GENERATED_DIR)
    parser.add_argument("--seconds", type=int, default=900)
    parser.add_argument("--report", type=Path, default=None)
    parser.add_argument("--compile", action="store_true",
                        help="build each generated module; they are written "
                             "outside the theory, so this copies one in, "
                             "builds it, and removes it again")
    arguments = parser.parse_args()
    if not arguments.set and not arguments.specs:
        parser.error("one of --set or --specs is required")
    arguments.out_dir.mkdir(parents=True, exist_ok=True)
    records = []
    for spec in (json.loads(arguments.specs.read_text())
                 if arguments.specs else []):
        text, name = from_spec(spec, arguments.extra_import)
        target = arguments.out_dir / f"Generated{name}.v"
        target.write_text(text)
        record = {"lemma": name, "generated": target.name,
                  "hand_lines_before": spec.get("hand_lines_before", 0),
                  "hand_lines_after": 0}
        if arguments.compile:
            record.update(compile_module(target, arguments.build_dir,
                                         arguments.seconds))
        records.append(record)
        print(f"{record['hand_lines_before']:>4} -> 0  "
              f"{'compiles' if record.get('compiled') else 'open':>8}  "
              f"{target.name}", flush=True)
    for line in (arguments.set.read_text().split("\n")
                 if arguments.set else []):
        if ":" not in line:
            continue
        module, lemma = line.split(":")[:2]
        path = Path(module)
        if not path.exists():
            path = PROOF_DIR / path.name
        text, name = generate(path, lemma, arguments.extra_import)
        target = arguments.out_dir / f"Generated{path.stem}.v"
        target.write_text(text)
        record = {"source": path.name, "lemma": lemma, "generated": target.name,
                  "hand_lines_before": len(find_proof(path, lemma).hand_lines),
                  "hand_lines_after": 0}
        if arguments.compile:
            record.update(compile_module(target, arguments.build_dir,
                                         arguments.seconds))
        records.append(record)
        print(f"{record['hand_lines_before']:>4} -> 0  "
              f"{'compiles' if record.get('compiled') else 'open':>8}  "
              f"{record.get('seconds', 0):>6}s  {target.name}", flush=True)
        for error in record.get("errors", [])[:1]:
            print(f"        {error[:110]}", flush=True)
    if arguments.report:
        arguments.report.parent.mkdir(parents=True, exist_ok=True)
        arguments.report.write_text(
            "".join(json.dumps(r) + "\n" for r in records))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
