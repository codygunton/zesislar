#!/usr/bin/env python3
"""Render ZesuSsz/Residuals/Block800d<blk>.v from verified residual goal dirs.

Usage:
  render_residual_module.py --block 6960 --goals DIR [--manifest MANIFEST.json] --out FILE

Each goal dir <blk>-<n>/ holds goal.v (the statement with a PROOF-SLOT) and
proof.v (goal.v with the slot filled and one Qed.). The module text of each
lemma is copied byte for byte from proof.v, from `Lemma` to `Qed.`. This
tool writes declarations around the copies (imports, hint registrations); it
never writes or edits proof text.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

SLOT = "(* PROOF-SLOT"
GENERATED = ("(* Generated by tools/residuals/render_residual_module.py. Do not edit.\n"
             "   Each lemma and its proof are copied verbatim from a checked goal dir. *)\n")
FORBIDDEN = re.compile(r"\b(Admitted|admit|Axiom|Abort|timeout|Timeout|give_up|Parameter)\b")
HEADER_LINE = re.compile(r"^(?:Require (?:Import|Export) [\w. ]+\.|From \w+ Require (?:Import|Export) [\w. ]+\."
                         r"|Local Open Scope \w+\.)$")
OLD_CORE = re.compile(r"\bZesuSsz\.Automation\.")
NAME = r"residual_(?P<block>[0-9a-f]{4})_[0-9a-f]+"
LEMMA = re.compile(
    r"\(\* goal (?P<goal>[0-9a-f]{4}-\d+): goal\.v sha256 (?P<goal_sha>[0-9a-f]{64}), "
    r"proof\.v sha256 (?P<proof_sha>[0-9a-f]{64}) \*\)\n"
    r"(?P<body>Lemma (?P<name>" + NAME + r") :\n.*?\nProof\.\n.*?Qed\.)\n"
    r"#\[export\] Hint Resolve (?P<hint>\w+) : zesu_residual\.\n", re.S)


class RenderError(ValueError):
    pass


def module_name(block):
    return "Block800d" + block


def goal_ids(goals, block, manifest=None):
    if manifest:
        data = json.loads(Path(manifest).read_text())
        if data.get("block") not in (None, block):
            raise RenderError("The manifest is for block %s." % data.get("block"))
        ids = [g["id"] for g in data["goals"]]
    else:
        ids = [p.name for p in Path(goals).iterdir()
               if p.is_dir() and re.fullmatch(re.escape(block) + r"-\d+", p.name)]
    ids = sorted(ids, key=lambda i: int(i.rsplit("-", 1)[1]))
    if not ids:
        raise RenderError("No goal dirs for block %s." % block)
    return ids


def read_goal(directory):
    """Return (header lines, lemma text, goal sha, proof sha) of one goal dir."""
    goal_path, proof_path = directory / "goal.v", directory / "proof.v"
    goal, proof = goal_path.read_text(), proof_path.read_text()
    if SLOT not in goal:
        raise RenderError("%s: goal.v has no PROOF-SLOT." % directory.name)
    head = goal[:goal.index(SLOT)]
    if not proof.startswith(head):
        raise RenderError("%s: proof.v does not start with the goal.v statement." % directory.name)
    rest = proof[len(head):]
    if FORBIDDEN.search(rest):
        raise RenderError("%s: proof.v uses a forbidden command." % directory.name)
    if rest.count("Qed.") != 1 or not rest.rstrip().endswith("Qed."):
        raise RenderError("%s: proof.v must end with exactly one Qed." % directory.name)
    start = head.find("\nLemma residual_")
    if start < 0:
        raise RenderError("%s: goal.v has no residual lemma." % directory.name)
    lemma = proof[start + 1:].rstrip()
    imports = []
    for line in head[:start].splitlines():
        if line.startswith(("Definition", "Global ", "  ", "    ", "#[")) or not line.strip():
            continue
        if not HEADER_LINE.match(line):
            raise RenderError("%s: unexpected preamble line: %s" % (directory.name, line))
        imports.append(line)
    if "Local Open Scope Z_scope." not in imports:
        raise RenderError("%s: goal.v does not open Z_scope." % directory.name)
    sha = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
    return imports, lemma, sha(goal_path), sha(proof_path)


def render_module(block, header, lemmas):
    """header: import lines; lemmas: list of dicts with goal, goal_sha, proof_sha, name, body."""
    out = [GENERATED, "\n".join(header), "\n"]
    for row in lemmas:
        out.append("\n(* goal %s: goal.v sha256 %s, proof.v sha256 %s *)\n%s\n"
                   "#[export] Hint Resolve %s : zesu_residual.\n"
                   % (row["goal"], row["goal_sha"], row["proof_sha"], row["body"], row["name"]))
    return "".join(out)


def parse_module(text):
    """Split a rendered module into (block, header lines, lemma rows); raise on any other shape."""
    if not text.startswith(GENERATED):
        raise RenderError("The module lacks the generated header.")
    rest = text[len(GENERATED):]
    header_text, sep, body = rest.partition("\n\n")
    if not sep:
        raise RenderError("The module has no lemmas.")
    header = header_text.split("\n")
    for line in header:
        if not HEADER_LINE.match(line) or OLD_CORE.search(line):
            raise RenderError("Invalid header line: %s" % line)
    rows, position = [], 0
    while position < len(body):
        match = LEMMA.match(body, position)
        if not match:
            raise RenderError("Invalid lemma block at offset %d." % position)
        if match["hint"] != match["name"]:
            raise RenderError("The hint does not name its lemma: %s." % match["name"])
        proof = match["body"].split("\nProof.\n", 1)[1]
        if FORBIDDEN.search(proof) or proof.count("Qed.") != 1:
            raise RenderError("Invalid proof of %s." % match["name"])
        rows.append(dict(goal=match["goal"], goal_sha=match["goal_sha"], proof_sha=match["proof_sha"],
                         name=match["name"], block=match["block"], body=match["body"]))
        position = match.end()
        if position < len(body):
            if body[position] != "\n":
                raise RenderError("Lemma blocks must be separated by one blank line.")
            position += 1
    if not rows:
        raise RenderError("The module has no lemmas.")
    blocks = {row["block"] for row in rows}
    if len(blocks) != 1:
        raise RenderError("A residual module serves one block.")
    if len({row["name"] for row in rows}) != len(rows):
        raise RenderError("A lemma name repeats.")
    block = blocks.pop()
    if render_module(block, header, rows) != text:
        raise RenderError("The module does not round-trip through the renderer.")
    return block, header, rows


def render_from_goals(block, goals, manifest=None):
    header, rows = None, []
    for goal in goal_ids(goals, block, manifest):
        imports, lemma, goal_sha, proof_sha = read_goal(Path(goals) / goal)
        if header is None:
            header = imports
        elif imports != header:
            raise RenderError("%s: its imports differ from the block's other goals." % goal)
        name = re.match(r"Lemma (\S+)", lemma)[1]
        if not re.fullmatch(NAME, name) or not name.startswith("residual_%s_" % block):
            raise RenderError("%s: unexpected lemma name %s." % (goal, name))
        rows.append(dict(goal=goal, goal_sha=goal_sha, proof_sha=proof_sha, name=name, body=lemma))
    text = render_module(block, pin_shared_modules(header, rows), rows)
    parse_module(text)
    return text


ROOT = Path(__file__).resolve().parents[2]


def shared_core_modules(root=ROOT):
    """Module names present in both the frozen core and Automation2."""
    frozen = {p.stem for p in (Path(root) / "ZesuSsz/Automation").rglob("*.v")}
    current = {p.stem for p in (Path(root) / "ZesuSsz/Automation2").rglob("*.v")}
    return frozen & current


def pin_shared_modules(header, rows, shared=None):
    """Import the Automation2 module behind each shared short name a lemma uses.

    A copied lemma may write `ByteWindowFold.x`; when the frozen core's module
    of that name is also in scope, the short name can resolve to it. Importing
    the Automation2 module last makes the short name resolve to Automation2.
    The statements and proofs are not changed.
    """
    shared = shared_core_modules() if shared is None else shared
    used = sorted({m.group(1) for row in rows for m in re.finditer(
        r"(?<![\w.'])(%s)\.[A-Za-z_]" % "|".join(map(re.escape, sorted(shared))),
        row["body"])} if shared else set())
    pins = ["Require Import ZesuSsz.Automation2.%s." % name for name in used]
    pins = [line for line in pins if line not in header]
    if not pins:
        return header
    scope = [i for i, line in enumerate(header) if line.startswith("Local Open Scope")]
    at = scope[0] if scope else len(header)
    return header[:at] + pins + header[at:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--block", required=True)
    ap.add_argument("--goals", required=True)
    ap.add_argument("--manifest")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    try:
        text = render_from_goals(a.block, a.goals, a.manifest)
    except RenderError as error:
        sys.exit("render_residual_module: %s" % error)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(text)
    print("wrote %s (%d lemmas)" % (a.out, text.count("#[export] Hint Resolve")))


if __name__ == "__main__":
    main()
