  intros Hin Hlookup. apply approved_code_key_resolves.
  unfold approvedContractCodeKeys, approvedInstructions.
  apply elem_of_list_fmap. exists (Z_to_bv 64 address, trace).
  split; first reflexivity.
  apply elem_of_list_fmap. exists (address, trace).
  split; first reflexivity.
  apply elem_of_app. right.
  unfold approvedIndexInstructions.
