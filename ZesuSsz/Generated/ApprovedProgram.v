Definition approvedInstructions : list (Z * isla_trace) :=
  approvedContractSourceInstructions ++ approvedIndexInstructions.

Definition approvedProgram : gmap addr isla_trace :=
  <[ BV 64 0x14cb0 := IslaTraces.main.a14cb0.a14cb0 ]>
    (list_to_map (List.map (fun item => (Z_to_bv 64 item.1, item.2))
      approvedInstructions)).

Lemma approved_main_instruction :
  approvedProgram !! BV 64 0x14cb0 =
    Some IslaTraces.main.a14cb0.a14cb0.
Proof. apply lookup_insert. Qed.


Definition approvedContractCodeKeys : list addr :=
  (List.map (fun item => (Z_to_bv 64 item.1, item.2)) approvedInstructions).*1.

Lemma approved_code_key_resolves address :
  address ∈ approvedContractCodeKeys ->
  exists trace, approvedProgram !! address = Some trace.
Proof.
  intros Hkey.
  have Hdom : address ∈ dom
      (list_to_map (List.map (fun item => (Z_to_bv 64 item.1, item.2))
        approvedInstructions) : gmap addr isla_trace).
  { rewrite dom_list_to_map elem_of_list_to_set. exact Hkey. }
  apply elem_of_dom in Hdom as [trace Hlookup].
  destruct (decide (address = BV 64 0x14cb0)) as [->|Hne].
  - exists IslaTraces.main.a14cb0.a14cb0. exact approved_main_instruction.
  - exists trace. unfold approvedProgram. rewrite lookup_insert_ne; done.
Qed.

Print Assumptions approved_code_key_resolves.

Lemma approved_source_code_resolves address trace :
  (address, trace) ∈ approvedContractSourceInstructions ->
  exists actual, approvedProgram !! Z_to_bv 64 address = Some actual.
Proof.
  intros Hin. apply approved_code_key_resolves.
  unfold approvedContractCodeKeys, approvedInstructions.
  apply elem_of_list_fmap. exists (Z_to_bv 64 address, trace).
  split; first reflexivity.
  apply elem_of_list_fmap. exists (address, trace).
  split; first reflexivity.
  apply elem_of_app. left. exact Hin.
Qed.

Lemma approved_index_address_resolves address trace :
  address ∈ approvedIndexAddresses ->
  IslaTraces.write_success_blocks.Index.lookup address = Some trace ->
  exists actual, approvedProgram !! Z_to_bv 64 address = Some actual.
