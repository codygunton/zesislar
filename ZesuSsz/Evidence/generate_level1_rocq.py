#!/usr/bin/env python3
"""Generate Rocq constants for the exact Level 1 binary regions."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


NAMES = {
    "read_input": "readInput",
    "zkvm_exit": "zkvmExit",
    "alt_fl_alloc.get": "allocatorGet",
    "ssz_decode_root.decodeInput": "decodeInput",
    "ssz_decode_observation.writeSuccess": "writeSuccess",
    "ssz_decode_observation.writeFailure": "writeFailure",
}


def pc_ranges(values: list[int]) -> list[tuple[int, int]]:
    if values != sorted(set(values)):
        raise ValueError("instruction PCs must be sorted and unique")
    ranges: list[tuple[int, int]] = []
    for pc in values:
        if pc % 4:
            raise ValueError(f"instruction PC is not four-byte aligned: {pc:#x}")
        if ranges and pc == ranges[-1][1]:
            ranges[-1] = (ranges[-1][0], pc + 4)
        else:
            ranges.append((pc, pc + 4))
    expanded = [pc for start, stop in ranges for pc in range(start, stop, 4)]
    if expanded != values:
        raise AssertionError("PC range compression changed the instruction set")
    return ranges


def rocq_ranges(values: list[int]) -> str:
    rows = [f"  ({start:#x}, {stop:#x})" for start, stop in pc_ranges(values)]
    return "[]" if not rows else "[\n" + ";\n".join(rows) + "\n]"


def rocq_zs(values: list[int]) -> str:
    return "[" + "; ".join(hex(value) for value in values) + "]"


def rocq_words(values: list[tuple[int, int]]) -> str:
    rows = [f"  ({pc:#x}, {word:#010x})" for pc, word in values]
    return "[\n" + ";\n".join(rows) + "\n]"


def generate(manifest: dict, cfg: dict) -> str:
    rows = {row["qualified"]: row for row in manifest["instances"]}
    if set(rows) != set(NAMES):
        raise ValueError("Level 1 Rocq generation requires the reviewed six-instance inventory")
    if cfg["artifact"]["sha256"] != manifest["artifact"]["sha256"]:
        raise ValueError("CFG and Level 1 manifest describe different load images")

    mains = [row for row in cfg["functionInstances"]
             if row["kind"] == "concrete" and row["parent"] is None
             and row["name"] == "ssz_decode_root.main"]
    if len(mains) != 1:
        raise ValueError("expected one concrete SSZ endpoint main instance")
    selected = {pc for row in rows.values() for pc in row["executionPcs"]}
    glue_pcs = sorted(set(mains[0]["pcs"]) - selected)
    if len(glue_pcs) != 24:
        raise ValueError("expected exactly 24 Level 0 parent-owned instructions")

    instructions = {
        instruction["pc"]: instruction
        for function in cfg["functions"]
        for block in function["blocks"]
        for instruction in block["instructions"]
    }
    if any(pc not in instructions for pc in glue_pcs):
        raise ValueError("Level 0 instruction is absent from the CFG instruction table")
    glue_words = []
    for pc in glue_pcs:
        encoded = bytes.fromhex(instructions[pc]["bytes"])
        if len(encoded) != 4:
            raise ValueError(f"Level 0 instruction at {pc:#x} is not a four-byte word")
        glue_words.append((pc, int.from_bytes(encoded, "little")))

    lines = [
        "(* Generated by ZesuSsz/Evidence/generate_level1_rocq.py. *)",
        "From Coq Require Import Lists.List Strings.String ZArith.ZArith.",
        "Import ListNotations.",
        "Open Scope Z_scope.",
        "Open Scope string_scope.",
        "",
        "Definition PcRange := (Z * Z)%type.",
        f'Definition artifactIdentityScope : string := "{manifest["artifact"]["identityScope"]}".',
        f'Definition artifactSha256 : string := "{manifest["artifact"]["sha256"]}".',
        f"Definition mainEntry : Z := {mains[0]['entryPc']:#x}.",
        f"Definition mainGlueInstructionCount : nat := {len(glue_pcs)}.",
        f"Definition mainGluePcRanges : list PcRange := {rocq_ranges(glue_pcs)}.",
        f"Definition mainGlueWords : list (Z * Z) := {rocq_words(glue_words)}.",
        "",
    ]
    for pc, word in glue_words:
        lines.append(f"Definition mainGlueWordAt{pc:x} : Z := {word:#010x}.")
    lines.append("")

    for qualified, rocq_name in NAMES.items():
        row = rows[qualified]
        lines.extend([
            f"Definition {rocq_name}Entry : Z := {row['entryPc']:#x}.",
            f"Definition {rocq_name}OwnedInstructionCount : nat := {len(row['instructionPcs'])}.",
            f"Definition {rocq_name}AbsorbedInstructionCount : nat := {len(row['absorbedInstructionPcs'])}.",
            f"Definition {rocq_name}ExecutionInstructionCount : nat := {len(row['executionPcs'])}.",
            f"Definition {rocq_name}OwnedPcRanges : list PcRange := {rocq_ranges(row['instructionPcs'])}.",
            f"Definition {rocq_name}ExecutionPcRanges : list PcRange := {rocq_ranges(row['executionPcs'])}.",
            f"Definition {rocq_name}ExitPcs : list Z := {rocq_zs(row['exitPcs'])}.",
            "",
        ])

    decode_exits = rows["ssz_decode_root.decodeInput"]["exitPcs"]
    zkvm_exits = rows["zkvm_exit"]["exitPcs"]
    if len(decode_exits) != 1 or len(zkvm_exits) != 1:
        raise ValueError("decodeInput and zkvm_exit require one exact exit each")
    lines.extend([
        f"Definition zkvmExitTerminalPc : Z := {zkvm_exits[0]:#x}.",
        "Definition inputBufferAddress : Z := 0x2001a000.",
        "Definition ioContextAddress : Z := 0x2401a0b8.",
    ])

    indirect = cfg.get("reviewedIndirectCalls", [])
    if indirect:
        vtables = {row["vtable"] for row in indirect}
        targets = {row["callee"]: row["target"] for row in indirect}
        if len(vtables) != 1:
            raise ValueError("allocator indirect calls do not share one vtable")
        if set(targets) != {"alt_fl_alloc.alloc", "alt_fl_alloc.remap"}:
            raise ValueError("unexpected allocator methods in endpoint execution")
        lines.extend([
            f"Definition allocatorVtableAddress : Z := {vtables.pop():#x}.",
            f"Definition allocatorAllocAddress : Z := {targets['alt_fl_alloc.alloc']:#x}.",
            f"Definition allocatorRemapAddress : Z := {targets['alt_fl_alloc.remap']:#x}.",
        ])
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--cfg", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(json.loads(args.manifest.read_text()),
                                    json.loads(args.cfg.read_text())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
