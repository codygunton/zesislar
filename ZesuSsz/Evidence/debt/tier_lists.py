"""Write the lists the builder executes from one `inventory.py` run.

  tier1_remove_now.txt   every module tier 1 deletes, after the carve-outs
  carve_outs.txt         the lead's carve-outs and the helpers they keep,
                         with the tier each one moved to and why
"""

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--modules", required=True)
    parser.add_argument("--sha", required=True)
    args = parser.parse_args()
    records = json.loads(Path(args.modules).read_text())
    head = f"# root {args.sha}; generated by ZesuSsz/Evidence/debt/tier_lists.py\n"
    tier1 = sorted(m for m, r in records.items() if r["class"] == "remove now")
    (HERE / "tier1_remove_now.txt").write_text(head + "".join(m + "\n" for m in tier1))
    carve = sorted((r["why"], r["class"], m) for m, r in records.items()
                   if r["why"].startswith("carve-out"))
    (HERE / "carve_outs.txt").write_text(head + "".join(
        f"{m}\t{cls}\t{why}\n" for why, cls, m in carve))
    print(f"tier 1: {len(tier1)} modules; carve-outs: {len(carve)} modules")


if __name__ == "__main__":
    main()
